doc = fitz.open(pdf_path)

def get_doc_page_str(pdf_idx): # 0-indexed
    p = pdf_idx + 1
    if p == 1:
        return "ปกนอก"
    elif p <= 13:
        thai = ["ก", "ข", "ค", "ง", "จ", "ฉ", "ช", "ซ", "ฌ", "ญ", "ฎ", "ฏ", "ฐ"]
        return thai[p - 2]
    else:
        return str(p - 13)

print("=== 1. VERIFYING LIST OF TABLES (สารบัญตาราง) ===")
# Expected tables:
# ตารางที่ 2.1
# ตารางที่ 2.2
# ตารางที่ 2.3
# ตารางที่ 3.1
# ตารางที่ 4.1
# ตารางที่ 4.2
tables = [
    "ตารางที่ 2.1",
    "ตารางที่ 2.2",
    "ตารางที่ 2.3",
    "ตารางที่ 3.1",
    "ตารางที่ 4.1",
    "ตารางที่ 4.2"
]

for t in tables:
    found = []
    for i, page in enumerate(doc):
        # don't search in front matter (p < 14)
        if i < 13:
            continue
        txt = page.get_text()
        if t in txt:
            found.append((i+1, get_doc_page_str(i)))
    print(f"{t}: Actual document page = {found}")

