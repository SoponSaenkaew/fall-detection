doc = fitz.open(pdf_path)

# Let's map every page in PDF to its header page number
page_map = {}
for i, page in enumerate(doc):
    txt = page.get_text()
    lines = [l.strip() for l in txt.split('\n') if l.strip()]
    
    # check first line or top block
    header_num = None
    if lines:
        first = lines[0]
        # is first line a page number?
        if re.match(r"^(\d+|[ก-ฮ])$", first):
            header_num = first
    page_map[i + 1] = {
        "header": header_num,
        "first_lines": lines[:3]
    }

